#!/usr/bin/env python3
"""Create or verify the licence texts committed in packaging/licenses/.

    python3 packaging/tools/fetch_licenses.py            make missing files; fail on a changed one
    python3 packaging/tools/fetch_licenses.py --check    verify only (no network): every file matches SOURCES.json
    python3 packaging/tools/fetch_licenses.py --update   regenerate everything and record the new SHA-256 values
                                                         (after a pin bump, e.g. a new Prism/Qt/.NET version)

packaging/licenses/SOURCES.json lists every file and where it comes from:
  {"url": ...}                         downloaded as is
  {"pin": "sources/<id>", "member": p} one file out of a tarball pinned in packaging/pins.json
  {"generator": "qt-attributions"}     built from the qt_attribution.json files of the pinned Qt source tarballs
  {"nuget": "<id>/<version>/<file>"}   copied from the local NuGet package folder

Licence texts are not game content; they are committed so that a package build needs no extra downloads and
so that a change of any of them shows up in review.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tarfile
import tempfile
from pathlib import Path

PACKAGING = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PACKAGING))
import build_package as bp  # noqa: E402

LICENSES = PACKAGING / "licenses"

# qt_attribution.json entries that are not in the Windows MSVC build of qtbase/qtsvg/qtimageformats/qtnetworkauth
# Prism ships (other platforms, tests, build tools, the SQL plugin), matched against "<module>/<dir>" or the name.
QT_SKIP_PATHS = ("/wayland/", "/android", "/gradle", "/wasm", "/xcb", "/cocoa", "/testlib/", "/testinternal/",
                 "/dbus", "/cmake/3rdparty", "/util/", "/forkfd", "/sqlite", "/pixman")
QT_SKIP_NAMES = ("QEventDispatcher on macOS",)
QT_MODULES = ("qtbase", "qtsvg", "qtimageformats", "qtnetworkauth")
LICENSE_BASENAMES = ("license", "licence", "copying", "copyright", "notice", "patents")


def _pin(pins: dict, ref: str) -> dict:
    group, ident = ref.split("/", 1)
    for s in pins.get(group, []):
        if s["id"] == ident:
            return s
    raise SystemExit(f"pins.json has no {group} entry with id {ident!r}")


def _tar_member(path: Path, member: str) -> bytes:
    with tarfile.open(path) as t:
        f = t.extractfile(member)
        if f is None:
            raise SystemExit(f"{path.name} has no file {member}")
        return f.read()


def _norm(text: str) -> str:
    return text.replace("\r\n", "\n").rstrip() + "\n"


def qt_attributions(pins: dict, downloads: Path) -> bytes:
    version = pins["versions"]["qt"]
    entries, texts = [], {}
    for mod in QT_MODULES:
        tar_path = bp.fetch(_pin(pins, f"sources/{mod}"), downloads)
        root = f"{mod}-everywhere-src-{version}/"
        with tarfile.open(tar_path) as t:
            for m in t:
                if not m.isfile():
                    continue
                base = m.name.rsplit("/", 1)[-1]
                if base == "qt_attribution.json" or "/LICENSES/" in m.name or base.lower().startswith(LICENSE_BASENAMES) \
                        or "LICENSE" in base.upper():
                    texts[m.name] = t.extractfile(m).read()
        for name in sorted(n for n in texts if n.startswith(root) and n.endswith("/qt_attribution.json")):
            rel_dir = name[:-len("/qt_attribution.json")]
            if any(s in "/" + rel_dir[len(root):] + "/" for s in QT_SKIP_PATHS):
                continue
            data = json.loads(texts[name].decode("utf-8"), strict=False)
            for e in data if isinstance(data, list) else [data]:
                if e.get("Name") in QT_SKIP_NAMES:
                    continue
                entries.append((mod, root, rel_dir, e))
    out = [f"Qt {version}: third-party code inside the Qt libraries that Prism Launcher ships",
           "=" * 78, "",
           "Prism/Qt6*.dll and the Qt plugins in Prism/{platforms,styles,tls,imageformats,iconengines} contain the",
           "code listed below. Qt itself is LGPL-3.0-only (licenses/LGPL-3.0.txt); Qt Network Authorization",
           "(Prism/Qt6NetworkAuth.dll) is GPL-3.0-only (licenses/GPL-3.0.txt). Source: SOURCE.txt.",
           "",
           "Generated by packaging/tools/fetch_licenses.py from the qt_attribution.json files of the official Qt",
           f"{version} source tarballs ({', '.join(QT_MODULES)}). Entries for other platforms (Linux, macOS, Android,",
           "WebAssembly, Wayland, X11), for tests, build tools and the SQL plugin are left out.", ""]
    for mod, root, rel_dir, e in sorted(entries, key=lambda x: (x[0], x[2], x[3].get("Name", ""))):
        lic_id = e.get("LicenseId") or e.get("License") or "?"
        copyright_ = e.get("Copyright") or ""
        if isinstance(copyright_, list):
            copyright_ = "\n".join(copyright_)
        out += ["", "-" * 78, f"{e.get('Name')}" + (f" {e['Version']}" if e.get("Version") else ""),
                f"  licence: {lic_id}", f"  used: {' '.join((e.get('QtUsage') or '').split())}",
                f"  in the Qt source: {rel_dir}"]
        if e.get("Homepage"):
            out.append(f"  homepage: {e['Homepage']}")
        if copyright_.strip():
            out += ["  copyright:"] + [f"    {line.strip()}" for line in copyright_.strip().splitlines()]
        files = e.get("LicenseFiles") or ([e["LicenseFile"]] if e.get("LicenseFile") else [])
        bodies = []
        for lf in files:
            path = os.path.normpath(f"{rel_dir}/{lf}").replace("\\", "/")
            if path in texts:
                bodies.append((lf, texts[path].decode("utf-8", errors="replace")))
            else:
                bodies.append((lf, f"[{lf} is not in the {mod} tarball]\n"))
        if not bodies:                         # no file of its own: the SPDX text(s) from the module's LICENSES/
            for part in lic_id.replace("(", " ").replace(")", " ").split():
                if part in ("AND", "OR", "WITH"):
                    continue
                p = f"{root}LICENSES/{part}.txt"
                if p in texts:
                    bodies.append((f"LICENSES/{part}.txt", texts[p].decode("utf-8", errors="replace")))
        for lf, body in bodies:
            out += ["", f"  --- {lf} ---", "", _norm(body).rstrip()]
    return ("\n".join(out) + "\n").encode("utf-8")


def produce(spec: dict, pins: dict, downloads: Path) -> bytes:
    src = spec["from"]
    if "url" in src:
        tmp = Path(tempfile.mkdtemp(prefix="cth-lic-")) / "f"
        last = None
        for attempt in range(1, 6):
            try:
                bp._download(src["url"], tmp)
                return tmp.read_bytes()
            except OSError as e:                # gnu.org resets connections now and then
                last = e
                bp.log(f"  {src['url']} try {attempt}: {e}")
                import time
                time.sleep(attempt)
        raise SystemExit(f"cannot download {src['url']}: {last}")
    if "pin" in src:
        return _tar_member(bp.fetch(_pin(pins, src["pin"]), downloads), src["member"])
    if src.get("generator") == "qt-attributions":
        return qt_attributions(pins, downloads)
    if "nuget" in src:
        p = bp.nuget_root(None) / src["nuget"]
        if not p.is_file():
            raise SystemExit(f"{p} not found (restore the extractor with the matching .NET runtime pack first)")
        return p.read_bytes()
    raise SystemExit(f"{spec['path']}: unknown source {src}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify only, no network")
    ap.add_argument("--update", action="store_true", help="regenerate all and record new hashes")
    ap.add_argument("--downloads", default=str(PACKAGING / "downloads"))
    args = ap.parse_args(argv)
    spec_path = LICENSES / "SOURCES.json"
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    pins = bp.load_pins(PACKAGING / "pins.json")
    downloads = Path(args.downloads)
    bad = 0
    for f in spec["files"]:
        path = LICENSES / f["path"]
        have = bp.file_hashes(path)["sha256"] if path.is_file() else None
        if args.check:
            if have != f.get("sha256"):
                bp.log(f"MISMATCH {f['path']}: {have or 'missing'} != {f.get('sha256')}")
                bad += 1
            continue
        if have and have == f.get("sha256") and not args.update:
            continue
        bp.log(f"make {f['path']} from {f['from']}")
        data = produce(f, pins, downloads)
        new = bp.sha256_bytes(data)
        if f.get("sha256") and new != f["sha256"] and not args.update:
            bp.log(f"CHANGED {f['path']}: upstream now gives {new}, SOURCES.json says {f['sha256']} "
                   f"(review it, then run with --update)")
            bad += 1
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        f["sha256"] = new
    if args.update or not args.check:
        spec_path.write_text(json.dumps(spec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    bp.log("ok" if not bad else f"{bad} problem(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
