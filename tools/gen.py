#!/usr/bin/env python3
"""Generate code from the sheets: one record/struct per row, built from that row's columns.

Outputs (never edit them by hand; change the sheet and re-run):
  fabric/src/main/java/dev/crafttheft/gen/Sheets.java
  extractor/src/CthExtract.Core/Generated/Sources.g.cs

Refuses to generate while tools/preflight.py reports errors.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))


def sheet(name):
    with open(os.path.join(ROOT, "sheets", name + ".json"), encoding="utf-8") as f:
        return json.load(f)


def jstr(s):
    return json.dumps(s, ensure_ascii=False)


def jval(v, t):
    if t == "bool":
        return "true" if v else "false"
    if t == "int":
        return str(int(v))
    if t == "number":
        return repr(float(v)) + "f"
    return jstr(str(v))


JTYPE = {"string": "String", "enum": "String", "ref": "String", "int": "int", "number": "float", "bool": "boolean"}


def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def java_record(s, cls, skip=()):
    cols = [(c, d) for c, d in s["columns"].items() if c not in skip]
    fields = ", ".join(f"{JTYPE[d['type']]} {camel(c)}" for c, d in cols)
    out = [f"    /** Sheet '{s['sheet']}': {s.get('doc', '')} */",
           f"    public record {cls}({fields}) {{}}",
           f"    public static final List<{cls}> {s['sheet'].upper()} = List.of("]
    rows = []
    for r in s["rows"]:
        args = ", ".join(jval(r[c], d["type"]) for c, d in cols)
        rows.append(f"        new {cls}({args})")
    out.append(",\n".join(rows))
    out.append("    );")
    return "\n".join(out)


def gen_java():
    systems = sheet("systems")
    parts = [
        "// GENERATED by tools/gen.py from sheets/*.json. Do not edit: change the sheet and re-run.",
        "package dev.crafttheft.gen;",
        "",
        "import java.util.List;",
        "",
        "public final class Sheets {",
        "    private Sheets() {}",
        "",
        java_record(sheet("weapons"), "Weapon"),
        "",
        java_record(sheet("consumables"), "Consumable"),
        "",
        java_record(sheet("vehicles"), "Vehicle"),
        "",
        java_record(sheet("loot"), "Loot"),
        "",
        java_record(sheet("crimes"), "Crime"),
        "",
        java_record(sheet("wanted"), "Wanted"),
        "",
        java_record(sheet("sources"), "Source", skip=("locator", "fallback")),
        "",
        "    /** Sheet 'systems': one constant per row. */",
    ]
    for r in systems["rows"]:
        name = (r["system"] + "_" + "".join("_" + ch.lower() if ch.isupper() else ch for ch in r["key"])).upper()
        v = r["value"]
        if isinstance(v, bool):
            decl = f"boolean {name} = {'true' if v else 'false'}"
        elif isinstance(v, int):
            decl = f"int {name} = {v}"
        elif isinstance(v, float):
            decl = f"float {name} = {v!r}f"
        else:
            decl = f"String {name} = {jstr(v)}"
        parts.append(f"    /** {r['doc']} */")
        parts.append(f"    public static final {decl};")
    parts.append("}")
    path = os.path.join(ROOT, "fabric", "src", "main", "java", "dev", "crafttheft", "gen", "Sheets.java")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    return path


def cs_str(s):
    return "@\"" + str(s).replace("\"", "\"\"") + "\""


def gen_cs():
    s = sheet("sources")
    lines = [
        "// GENERATED by tools/gen.py from sheets/sources.json. Do not edit: change the sheet and re-run.",
        "namespace CthExtract.Core.Generated;",
        "",
        "/// <summary>One row of the sources sheet: a piece of game content and where it goes in the cache.</summary>",
        "public sealed record SourceRow(string Id, string Game, string Kind, string Locator, string Fallback, int MaxTris, string Out, string Placeholder);",
        "",
        "public static class Sources",
        "{",
        "    public static readonly IReadOnlyList<SourceRow> All = new SourceRow[]",
        "    {",
    ]
    for r in s["rows"]:
        lines.append("        new(" + ", ".join([
            cs_str(r["id"]), cs_str(r["game"]), cs_str(r["kind"]), cs_str(r["locator"]),
            cs_str(r["fallback"]), str(r["maxTris"]), cs_str(r["out"]), cs_str(r["placeholder"])]) + "),")
    lines += ["    };", "", "    public static IEnumerable<SourceRow> ForGame(string game) => All.Where(r => r.Game == game);", "}"]
    # weapon ids for stats extraction
    w = sheet("weapons")
    lines += ["", "public static class WeaponIds", "{",
              "    public static readonly IReadOnlyList<string> All = new[] { " + ", ".join(cs_str(r["id"]) for r in w["rows"]) + " };",
              "}"]
    path = os.path.join(ROOT, "extractor", "src", "CthExtract.Core", "Generated", "Sources.g.cs")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


def main():
    rc = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "preflight.py")], capture_output=True, text=True)
    if rc.returncode != 0:
        sys.stdout.write(rc.stdout)
        print("gen: preflight has errors; fix the sheets first")
        return 1
    print("wrote", gen_java())
    print("wrote", gen_cs())
    return 0


if __name__ == "__main__":
    sys.exit(main())
