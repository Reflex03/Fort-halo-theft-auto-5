#!/usr/bin/env bash
# Build cthextract.exe (GPL-3.0-only): restore, run every test project, then publish one self-contained win-x64
# single-file executable into extractor/dist/.
#
#   extractor/build.sh               full build (tests must pass before anything is published)
#   CTH_SKIP_TESTS=1 extractor/build.sh   publish without running tests (local iteration only)
#   CTH_TESTS="Cli Halo" extractor/build.sh   run only these test projects (names after "CthExtract.", ".Tests")
#
# Needs the .NET 10 SDK. Works on Linux, macOS and Windows (Git Bash); the output is always the Windows exe.
# Nothing here reads or writes game files; tests use synthetic data generated by the test code.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"
CONFIG="${CONFIG:-Release}"
RID="win-x64"
DIST="$HERE/dist"
LOGDIR="$HERE/bin/build-logs"   # bin/ is git-ignored
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1 DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1

say() { printf '\n== %s\n' "$*"; }

say "dotnet $(dotnet --version) | config $CONFIG | $(date -u +%FT%TZ)"
mkdir -p "$LOGDIR"

say "restore"
dotnet restore CthExtract.slnx --nologo -v minimal

if [[ "${CTH_SKIP_TESTS:-0}" != "1" ]]; then
  say "test"
  failed=()
  passed=()
  for proj in tests/*/*.Tests.csproj; do
    name="$(basename "$proj" .csproj)"
    short="${name#CthExtract.}"; short="${short%.Tests}"
    if [[ -n "${CTH_TESTS:-}" && " ${CTH_TESTS} " != *" ${short} "* ]]; then
      echo "skip $name (CTH_TESTS=${CTH_TESTS})"
      continue
    fi
    echo "-- $name"
    start=$(date +%s)
    if dotnet test "$proj" -c "$CONFIG" --nologo -v quiet >"$LOGDIR/$name.log" 2>&1; then
      passed+=("$name")
      result="ok"
    else
      failed+=("$name")
      result="FAILED"
    fi
    summary="$(grep -E '^(Passed|Failed)!|Total tests|error' "$LOGDIR/$name.log" | tail -3 | tr '\n' ' ')"
    echo "   $result in $(( $(date +%s) - start )) s: $summary"
  done
  say "tests: ${#passed[@]} project(s) passed, ${#failed[@]} failed"
  if (( ${#failed[@]} > 0 )); then
    for f in "${failed[@]}"; do
      echo "--- $f (last 40 lines of $LOGDIR/$f.log)"
      tail -40 "$LOGDIR/$f.log"
    done
    echo "not publishing: fix the failing tests (or CTH_SKIP_TESTS=1 for a local, untested build)" >&2
    exit 1
  fi
else
  say "tests skipped (CTH_SKIP_TESTS=1)"
fi

say "publish $RID single-file"
rm -rf "$DIST"
dotnet publish src/CthExtract/CthExtract.csproj -c Release -r "$RID" --self-contained \
  -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true \
  -p:EnableCompressionInSingleFile=false -p:DebugType=none \
  --nologo -v minimal -o "$DIST" | tee "$LOGDIR/publish.log"

EXE="$DIST/cthextract.exe"
[[ -f "$EXE" ]] || { echo "publish produced no $EXE" >&2; exit 1; }

say "check $EXE"
# PE header: subsystem 2 = Windows GUI (no console window), machine 0x8664 = x64
python3 - "$EXE" <<'PY' || { echo "PE check failed" >&2; exit 1; }
import struct, sys
b = open(sys.argv[1], 'rb').read(4096)
assert b[:2] == b'MZ', 'no MZ header'
pe = struct.unpack_from('<I', b, 0x3C)[0]
assert b[pe:pe + 4] == b'PE\0\0', 'no PE signature'
machine = struct.unpack_from('<H', b, pe + 4)[0]
subsystem = struct.unpack_from('<H', b, pe + 24 + 68)[0]
print(f'PE machine 0x{machine:04x}, subsystem {subsystem} ({"GUI" if subsystem == 2 else "console" if subsystem == 3 else "?"})')
assert machine == 0x8664, 'not x64'
assert subsystem == 2, 'not a GUI-subsystem exe: it would open a console window'
PY
others="$(find "$DIST" -type f ! -name cthextract.exe | sed "s#^$DIST/##" | sort | tr '\n' ' ')"
[[ -z "$others" ]] || echo "note: dist also holds: $others"
size=$(wc -c <"$EXE")
( cd "$DIST" && sha256sum cthextract.exe > cthextract.exe.sha256 )
echo "cthextract.exe: $size bytes ($(( size / 1024 / 1024 )) MiB), sha256 $(cut -d' ' -f1 "$DIST/cthextract.exe.sha256")"

# Record which source the exe was built from: packaging/build_package.py --release refuses an exe whose extractor/
# tree is not the release commit's (the GPL-3.0 corresponding source must be exactly that commit's extractor/).
python3 - "$HERE" "$DIST/cthextract.source.json" "$(cut -d' ' -f1 "$DIST/cthextract.exe.sha256")" <<'PY'
import json, subprocess, sys
here, out, sha = sys.argv[1:4]
def git(*a):
    r = subprocess.run(["git", "-C", here, *a], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None
status = git("status", "--porcelain", "--untracked-files=normal", "--", ".")
stamp = {"commit": git("rev-parse", "HEAD"), "extractorTree": git("rev-parse", "HEAD:extractor"),
         "dirty": status is None or status != "", "sha256": sha}
open(out, "w", encoding="utf-8").write(json.dumps(stamp, indent=1) + "\n")
print(f"source stamp: commit {stamp['commit']}, extractor tree {stamp['extractorTree']}"
      + (" (UNCOMMITTED changes: not releasable)" if stamp["dirty"] else ""))
PY
say "done: $EXE"
